// Generates migrations/0002_seed.sql from seed/**/*.md (frontmatter + markdown body).
// Re-run after editing the seed files: node scripts/seed-from-content.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as yaml from 'js-yaml';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === '' ? 'NULL' : Number(v));
const b = (v) => (v ? 1 : 0);

function readMd(dir) {
  const out = [];
  for (const lang of ['en', 'nl']) {
    for (const f of readdirSync(join(dir, lang)).filter((f) => f.endsWith('.md'))) {
      const raw = readFileSync(join(dir, lang, f), 'utf8');
      const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
      out.push({ slug: f.replace(/\.md$/, ''), lang, data: yaml.load(m[1]), body: (m[2] ?? '').trim() });
    }
  }
  return out;
}

const lines = ['-- Generated by scripts/seed-from-content.mjs. Safe to re-run: INSERT OR IGNORE keeps admin edits.'];
for (const s of readMd('seed/services')) {
  const d = s.data;
  const prices = JSON.stringify((d.prices ?? []).map((p) => ({ label: p.label, ...(p.from ? { from: p.from } : {}), ...(p.text ? { text: p.text } : {}) })));
  lines.push(
    `INSERT OR IGNORE INTO services (anchor, lang, sort, icon, title, headline, summary, cta, cta_topic, secondary, card_price, prices, body) VALUES (` +
      [q(d.anchor), q(s.lang), n(d.order), q(d.icon), q(d.title), q(d.headline), q(d.summary), q(d.cta), q(d.ctaTopic ?? null), b(d.secondary), n(d.cardPrice), q(prices), q(s.body)].join(', ') +
      ');',
  );
}
for (const w of readMd('seed/work')) {
  const d = w.data;
  lines.push(
    `INSERT OR IGNORE INTO work (slug, lang, sort, name, summary, tags, url, pillar, nda, featured) VALUES (` +
      [q(w.slug), q(w.lang), n(d.order), q(d.name), q(d.summary), q(JSON.stringify(d.tags ?? [])), q(d.url ?? null), q(d.pillar), b(d.nda), b(d.featured)].join(', ') +
      ');',
  );
}
writeFileSync('migrations/0002_seed.sql', lines.join('\n') + '\n');
console.log(`migrations/0002_seed.sql written (${lines.length - 1} rows)`);
